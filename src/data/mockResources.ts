export function computeSummaryStats(resources: Resource[]) {
  const categoriesSet = new Set(resources.map(r => r.category));
  return {
    total: resources.length,
    available: resources.filter(r => r.status === 'available').length,
    inUse: resources.filter(r => r.status === 'in_use').length,
    maintenance: resources.filter(r => r.status === 'maintenance').length,
    categoriesCount: categoriesSet.size,
    requiresVerificationCount: resources.filter(r => r.requiresVerification).length,
  };
}
